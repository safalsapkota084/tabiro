export const dictionaries = Object.fromEntries(['en', 'ja', 'fr'].map((lang, index) => [lang, Object.fromEntries(Object.entries(messages).map(([key, values]) => [key, values[index]]))]));
export function resolveLocale(value) {
  const lang = typeof value === 'string' ? value.toLowerCase().split('-')[0] : 'en';
  return Object.hasOwn(dictionaries, lang) ? lang : 'en';
}
export function translate(lang, key, values = {}) {
  const message = dictionaries[resolveLocale(lang)][key];
  if (message === undefined) throw new Error(`Missing translation: ${key}`);
  return message.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}
